create table if not exists public.inventory_items (
  id bigint generated by default as identity primary key,
  name text not null unique,
  unit text not null default 'pcs',
  current_stock numeric(14,3) not null default 0,
  low_stock_level numeric(14,3) not null default 0,
  cost_per_unit numeric(14,4) not null default 0,
  supplier text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inventory_nonnegative_threshold check (low_stock_level >= 0),
  constraint inventory_nonnegative_cost check (cost_per_unit >= 0)
);

create table if not exists public.product_recipes (
  id bigint generated by default as identity primary key,
  product_name text not null,
  size text,
  temperature text,
  inventory_item_id bigint not null references public.inventory_items(id) on delete cascade,
  quantity_used numeric(14,3) not null check (quantity_used > 0),
  created_at timestamptz not null default now(),
  unique nulls not distinct (product_name, size, temperature, inventory_item_id)
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  inventory_item_id bigint not null references public.inventory_items(id) on delete cascade,
  movement_type text not null check (movement_type in ('opening','restock','sale','waste','correction','return')),
  quantity numeric(14,3) not null,
  balance_after numeric(14,3) not null,
  reference text,
  notes text,
  order_id bigint,
  created_at timestamptz not null default now()
);

create index if not exists inventory_movements_item_created_idx on public.inventory_movements(inventory_item_id, created_at desc);
create index if not exists product_recipes_lookup_idx on public.product_recipes(product_name, size, temperature);

alter table public.orders add column if not exists inventory_processed_at timestamptz;

create or replace function public.set_inventory_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists inventory_items_updated_at on public.inventory_items;
create trigger inventory_items_updated_at
before update on public.inventory_items
for each row execute function public.set_inventory_updated_at();

create or replace function public.adjust_inventory_stock(
  p_inventory_item_id bigint,
  p_quantity numeric,
  p_movement_type text,
  p_reference text default null,
  p_notes text default null
)
returns numeric
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance numeric;
begin
  if p_quantity = 0 then raise exception 'Quantity cannot be zero'; end if;
  if p_movement_type not in ('opening','restock','sale','waste','correction','return') then
    raise exception 'Invalid movement type';
  end if;

  update public.inventory_items
  set current_stock = current_stock + p_quantity
  where id = p_inventory_item_id
  returning current_stock into v_balance;

  if v_balance is null then raise exception 'Inventory item not found'; end if;

  insert into public.inventory_movements(inventory_item_id,movement_type,quantity,balance_after,reference,notes)
  values(p_inventory_item_id,p_movement_type,p_quantity,v_balance,p_reference,p_notes);

  return v_balance;
end;
$$;

create or replace function public.process_completed_order_inventory()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item record;
  v_recipe record;
  v_deduction numeric;
  v_balance numeric;
begin
  if new.status <> 'completed' or new.inventory_processed_at is not null then return new; end if;

  for v_item in
    select product_name, size, temperature, quantity
    from public.order_items
    where order_id = new.id
  loop
    for v_recipe in
      select inventory_item_id, quantity_used
      from public.product_recipes
      where lower(product_name) = lower(v_item.product_name)
        and (size is null or lower(size) = lower(coalesce(v_item.size,'')))
        and (temperature is null or lower(temperature) = lower(coalesce(v_item.temperature::text,'')))
    loop
      v_deduction := v_recipe.quantity_used * greatest(v_item.quantity, 1);

      update public.inventory_items
      set current_stock = current_stock - v_deduction
      where id = v_recipe.inventory_item_id
      returning current_stock into v_balance;

      insert into public.inventory_movements(
        inventory_item_id,movement_type,quantity,balance_after,reference,notes,order_id
      ) values (
        v_recipe.inventory_item_id,'sale',-v_deduction,v_balance,new.order_number,
        v_item.product_name || coalesce(' · ' || v_item.size,''),new.id
      );
    end loop;
  end loop;

  new.inventory_processed_at := now();
  return new;
end;
$$;

drop trigger if exists orders_inventory_completion on public.orders;
create trigger orders_inventory_completion
before update of status on public.orders
for each row execute function public.process_completed_order_inventory();

