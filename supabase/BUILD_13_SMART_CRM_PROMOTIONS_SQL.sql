-- BUILD 13: Smart Business Assistant, CRM notes and promotion campaigns
create table if not exists public.crm_customer_notes (
  id bigint generated by default as identity primary key,
  mobile text not null unique,
  note text not null default '',
  tag text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotions (
  id bigint generated by default as identity primary key,
  name text not null,
  code text unique,
  discount_type text not null default 'percent' check (discount_type in ('percent','fixed','bogo')),
  discount_value numeric not null default 0,
  description text,
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.crm_customer_notes enable row level security;
alter table public.promotions enable row level security;

drop policy if exists "authenticated manage crm notes" on public.crm_customer_notes;
create policy "authenticated manage crm notes" on public.crm_customer_notes for all to authenticated using (true) with check (true);
drop policy if exists "authenticated manage promotions" on public.promotions;
create policy "authenticated manage promotions" on public.promotions for all to authenticated using (true) with check (true);
