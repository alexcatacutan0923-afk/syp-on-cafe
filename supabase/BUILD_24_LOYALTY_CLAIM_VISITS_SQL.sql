-- One calendar visit is recorded per member per Manila calendar date.
create or replace function public.add_loyalty_stamp(p_member_code text, p_count integer default 1)
returns public.loyalty_members
language plpgsql security definer set search_path = public
as $$
declare
  v_member public.loyalty_members;
  v_visit_date date := (now() at time zone 'Asia/Manila')::date;
  v_visit_added integer := 0;
begin
  if greatest(0, coalesce(p_count, 0)) = 0 then
    select * into v_member from public.loyalty_members
    where lower(member_code) = lower(trim(p_member_code));
    if not found then raise exception 'Member not found'; end if;
    return v_member;
  end if;

  insert into public.loyalty_visits(member_code, visit_date, visited_at, source)
  values (upper(trim(p_member_code)), v_visit_date, now(), 'pos')
  on conflict (member_code, visit_date) do nothing;
  get diagnostics v_visit_added = row_count;

  update public.loyalty_members
  set stamps = stamps + greatest(0, p_count),
      total_stamps = greatest(coalesce(total_stamps, 0), 0) + greatest(0, p_count),
      total_visits = total_visits + v_visit_added,
      last_stamp_date = v_visit_date,
      status = case when stamps + greatest(0, p_count) >= 10 then 'FREE DRINK READY' else 'Active' end,
      updated_at = now()
  where lower(member_code) = lower(trim(p_member_code))
  returning * into v_member;

  if not found then raise exception 'Member not found'; end if;
  return v_member;
end;
$$;

create or replace function public.claim_loyalty_free_drink(
  p_member_code text,
  p_receipt_no text default null,
  p_cashier text default null
) returns public.loyalty_members
language plpgsql security definer set search_path = public
as $$
declare
  v_member public.loyalty_members;
  v_visit_date date := (now() at time zone 'Asia/Manila')::date;
  v_visit_added integer := 0;
begin
  insert into public.loyalty_visits(member_code, visit_date, visited_at, source, receipt_no)
  values (upper(trim(p_member_code)), v_visit_date, now(), 'reward-claim', nullif(trim(coalesce(p_receipt_no, '')), ''))
  on conflict (member_code, visit_date) do nothing;
  get diagnostics v_visit_added = row_count;

  update public.loyalty_members
  set stamps = stamps - 10,
      rewards_claimed = coalesce(rewards_claimed, 0) + 1,
      total_visits = total_visits + v_visit_added,
      claim_status = 'Claimed',
      claimed_date = (now() at time zone 'Asia/Manila')::date,
      status = case when stamps - 10 >= 10 then 'FREE DRINK READY' else 'Active' end,
      updated_at = now()
  where lower(member_code) = lower(trim(p_member_code))
    and stamps >= 10
  returning * into v_member;

  if not found then raise exception 'Member needs at least 10 stamps'; end if;

  insert into public.loyalty_reward_claims(member_code, reward_type, stamps_used, receipt_no, cashier)
  values (v_member.member_code, 'free_drink', 10, nullif(trim(coalesce(p_receipt_no, '')), ''), nullif(trim(coalesce(p_cashier, '')), ''));
  return v_member;
end;
$$;

create or replace function public.get_loyalty_visits(p_member_code text, p_month text default null)
returns table(visit_date date, visited_at timestamptz, source text, receipt_no text)
language sql security definer set search_path = public
as $$
  select v.visit_date, v.visited_at, v.source, v.receipt_no
  from public.loyalty_visits v
  where lower(v.member_code) = lower(trim(p_member_code))
    and (
      nullif(trim(coalesce(p_month, '')), '') is null
      or to_char(v.visit_date, 'YYYY-MM') = trim(p_month)
    )
  order by v.visit_date desc;
$$;

