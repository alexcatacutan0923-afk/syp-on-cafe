create table if not exists public.loyalty_visits (
  id bigint generated by default as identity primary key,
  member_code text not null,
  visit_date date not null,
  visited_at timestamptz not null default now(),
  source text not null default 'pos',
  receipt_no text,
  created_at timestamptz not null default now(),
  unique (member_code, visit_date)
);

create index if not exists loyalty_visits_member_date_idx
  on public.loyalty_visits (member_code, visit_date desc);

create table if not exists public.loyalty_reward_claims (
  id bigint generated by default as identity primary key,
  member_code text not null,
  reward_type text not null default 'free_drink',
  stamps_used integer not null default 10,
  receipt_no text,
  cashier text,
  claimed_at timestamptz not null default now()
);

alter table public.loyalty_members add column if not exists rewards_claimed integer not null default 0;
