create table if not exists public.community_reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  drink text not null,
  stars integer not null check (stars between 1 and 5),
  review_text text not null check (char_length(review_text) between 8 and 500),
  order_number text,
  badge text,
  owner_reply text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.coffee_moments (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  caption text not null check (char_length(caption) between 5 and 300),
  tag text not null default 'KaSYP Tambay',
  image_url text not null,
  storage_path text,
  likes integer not null default 0 check (likes >= 0),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.community_reviews enable row level security;
alter table public.coffee_moments enable row level security;

-- Public can read approved content and submit pending content.
drop policy if exists "Public read approved reviews" on public.community_reviews;
create policy "Public read approved reviews" on public.community_reviews for select using (status = 'approved');
drop policy if exists "Public submit pending reviews" on public.community_reviews;
create policy "Public submit pending reviews" on public.community_reviews for insert with check (status = 'pending');

drop policy if exists "Public read approved moments" on public.coffee_moments;
create policy "Public read approved moments" on public.coffee_moments for select using (status = 'approved');
drop policy if exists "Public submit pending moments" on public.coffee_moments;
create policy "Public submit pending moments" on public.coffee_moments for insert with check (status = 'pending');
drop policy if exists "Public like approved moments" on public.coffee_moments;
create policy "Public like approved moments" on public.coffee_moments for update using (status = 'approved') with check (status = 'approved');

-- Authenticated admin users can moderate all community content.
drop policy if exists "Authenticated manage reviews" on public.community_reviews;
create policy "Authenticated manage reviews" on public.community_reviews for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated manage moments" on public.coffee_moments;
create policy "Authenticated manage moments" on public.coffee_moments for all to authenticated using (true) with check (true);

-- Create the public image bucket in Dashboard > Storage if this insert is not permitted.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('coffee-moments', 'coffee-moments', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

-- Anyone can upload new photos; only authenticated admins can delete them.
drop policy if exists "Public upload coffee moments" on storage.objects;
create policy "Public upload coffee moments" on storage.objects for insert to anon, authenticated with check (bucket_id = 'coffee-moments');
drop policy if exists "Public read coffee moments" on storage.objects;
create policy "Public read coffee moments" on storage.objects for select to public using (bucket_id = 'coffee-moments');
drop policy if exists "Authenticated delete coffee moments" on storage.objects;
create policy "Authenticated delete coffee moments" on storage.objects for delete to authenticated using (bucket_id = 'coffee-moments');
